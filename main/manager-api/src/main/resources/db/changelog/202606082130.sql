CREATE TABLE IF NOT EXISTS `ai_memo_list` (
    `id` VARCHAR(32) NOT NULL COMMENT '服务端主键',
    `user_id` BIGINT NOT NULL COMMENT '所属用户ID',
    `memo_id` VARCHAR(64) NOT NULL COMMENT '客户端清单ID',
    `name` VARCHAR(100) NOT NULL COMMENT '清单名称',
    `color` VARCHAR(32) DEFAULT '#F8B800' COMMENT '清单颜色',
    `client_created_at` BIGINT DEFAULT 0 COMMENT '客户端创建时间毫秒',
    `client_updated_at` BIGINT DEFAULT 0 COMMENT '客户端更新时间毫秒',
    `deleted_at` BIGINT DEFAULT 0 COMMENT '客户端删除时间毫秒',
    `sort_order` BIGINT DEFAULT 0 COMMENT '客户端排序值',
    `creator` BIGINT COMMENT '创建者',
    `create_date` DATETIME COMMENT '创建时间',
    `updater` BIGINT COMMENT '更新者',
    `update_date` DATETIME COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_ai_memo_list_user_memo` (`user_id`, `memo_id`),
    KEY `idx_ai_memo_list_user` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='便单清单';

